# 目标：亲眼看懂 y_hat = Xw + b，以及平方损失是怎么算出来的

import torch

# ---------- 数据 ----------
# 3 套房子的特征，每行是 [面积(m^2), 房龄(年)]
X = torch.tensor([[100.,   5.],
                  [ 80.,  10.],
                  [120.,   2.]])

# 真实价格（万元）
y = torch.tensor([320., 230., 420.])

# ---------- 当前参数（先随便给的，还没训练）----------
w = torch.tensor([2.5, -6.0])   # w[1] 是负数：房龄越大越便宜
b = 140.0

# ---------- 零件 1：模型 ----------
# TODO(你): 算出 3 套房子的预测价格 y_hat
#   hint: torch.matmul(X, w) 得到形状 (3,)，再整体加 b
y_hat = torch.matmul(X, w) + b

print("预测值 y_hat =", y_hat)
print("真实值 y     =", y)

# ---------- 零件 2：损失函数 ----------
# TODO(你): 算出整个数据集上的平均损失 L
#   hint: 先算每个样本的 l = 0.5 * (y_hat - y)**2，再对 3 个样本求平均
L = torch.mean(0.5*(y_hat - y)**2)

print("整体损失 L   =", L)

